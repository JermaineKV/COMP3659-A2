#ifndef WORKER_H
#define WORKER_H

#include "globals.h"

// ============================================================================
// FUNCTION PROTOTYPES
// ============================================================================

/*
 * ========================================================================
 * FUNCTION: worker_function
 * ========================================================================
 * 
 * Main routine for worker threads.
 * 
 * ========================================================================
 */
void *worker_function(void *arg);

/*
 * ========================================================================
 * FUNCTION: init_thread_pool
 * ========================================================================
 * 
 * Initializes the thread pool and creates worker threads.
 * 
 * ========================================================================
 */
int init_thread_pool(Thread_Pool *pool, int num_workers);

/*
 * ========================================================================
 * FUNCTION: clean_thread_pool
 * ========================================================================
 * 
 * Shuts down and cleans up the thread pool.
 * 
 * ========================================================================
 */
void clean_thread_pool(Thread_Pool *pool);

/*
 * ========================================================================
 * FUNCTION: parse_http_request
 * ========================================================================
 * 
 * Parses the HTTP request to extract the filename.
 * 
 * ========================================================================
 */
int parse_http_request(const char* request_buffer, char* filename, size_t filename_size);

#endif // WORKER_H
